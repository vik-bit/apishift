"""Run the benchmark for each method and write docs/EVAL_RESULTS.md."""

from __future__ import annotations

import json
from datetime import date
from typing import Callable

from ..config import PROJECT_ROOT, Settings
from ..fix.llm import make_provider
from .benchmark import MODES, CaseScore, load_cases, run_case, summarise, to_json

NAMES = {"codemod": "Codemod only (no AI)", "llm-one-shot": "LLM one-shot (no tests)", "apishift": "**APIShift** (codemods + LLM + test-verified retries)"}


def _pct(a: int, b: int) -> str:
    return f"{a}/{b} ({100 * a / b:.0f}%)" if b else "-"


def write_markdown(results: dict[str, list[CaseScore]], model: str, n_cases: int) -> str:
    sums = {m: summarise(s) for m, s in results.items()}
    lines = [
        "# Evaluation results", "",
        f"_Generated by `apishift eval` on {date.today().isoformat()} · {n_cases} benchmark cases "
        f"(`bench/cases/`) · pandas 2.2 · strict mode (deprecation warnings count as failures) · LLM `{model}`._", "",
        "A case counts as **fixed** only if its tests pass afterwards and no removed API remains. A **negative** case "
        "(code that must not change, such as `list.append`) counts only if the file is left untouched.", "",
        "| Method | Cases fixed | Hard cases fixed | Negatives left alone | Needed a retry | LLM calls | Tokens | Time |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for m, s in sums.items():
        lines.append(f"| {NAMES.get(m, m)} | {_pct(s['fixed'], s['positive'])} | {_pct(s['hard_fixed'], s['hard'])} | "
                     f"{_pct(s['negatives_untouched'], s['negative'])} | {s['needed_retry']} | {s['llm_calls']} | "
                     f"{s['tokens']:,} | {s['seconds']}s |")
    lines += ["", "## Per case", "", "| Case | Kind | " + " | ".join(NAMES.get(m, m).replace("**", "") for m in results) + " |",
              "|---|---|" + "---|" * len(results)]
    by_case: dict[str, dict[str, CaseScore]] = {}
    for m, scores in results.items():
        for s in scores:
            by_case.setdefault(s.case, {})[m] = s
    for case, ms in by_case.items():
        first = next(iter(ms.values()))
        cells = []
        for m in results:
            s = ms.get(m)
            if s is None:
                cells.append("-")
            elif s.success:
                cells.append("✅" + (f" ({s.llm_attempts} tries)" if s.llm_attempts > 1 else ""))
            else:
                why = s.error or ("changed a negative case" if first.kind == "negative" and s.changed else
                                  "removed API remains" if s.remaining else "tests fail")
                cells.append(f"❌ {why}")
        lines.append(f"| `{case}` | {first.kind}, {first.difficulty} | " + " | ".join(cells) + " |")
    errors = [e for s in sums.values() for e in s["errors"]]
    if errors:
        lines += ["", "**Errors during the run:**", *[f"- {e}" for e in errors]]
    lines += ["", "Raw per-case numbers: `bench/results/results.json`.", ""]
    return "\n".join(lines)


def run_eval(modes: list[str], only: str | None = None, log: Callable[[str], None] = print) -> dict:
    settings = Settings()
    provider = make_provider(settings)
    cases = load_cases(only=only)
    results: dict[str, list[CaseScore]] = {}
    for mode in modes:
        if MODES[mode].use_llm and provider is None:
            log(f"skipping {mode}: no LLM key configured")
            continue
        log(f"== {mode} ==")
        scores = []
        for c in cases:
            s = run_case(c, mode, provider if MODES[mode].use_llm else None)
            log(f"  {'ok  ' if s.success else 'FAIL'} {c.id}" + (f"  ({s.llm_attempts} attempts)" if s.llm_attempts > 1 else "")
                + (f"  {s.error}" if s.error else ""))
            scores.append(s)
        results[mode] = scores
        log(f"  → {summarise(scores)['fixed']}/{summarise(scores)['positive']} fixed")
    out_dir = PROJECT_ROOT / "bench" / "results"
    out_dir.mkdir(parents=True, exist_ok=True)
    full = set(results) == set(MODES) and only is None
    name = "results.json" if full else f"partial-{'-'.join(results)}{'-' + only if only else ''}.json"
    (out_dir / name).write_text(json.dumps({
        "date": date.today().isoformat(), "model": settings.model,
        "summary": {m: summarise(s) for m, s in results.items()},
        "cases": {m: to_json(s) for m, s in results.items()},
    }, indent=2, ensure_ascii=False), encoding="utf-8")
    md = write_markdown(results, settings.model, len(cases))
    if full:  # only a complete run may replace the published results
        (PROJECT_ROOT / "docs" / "EVAL_RESULTS.md").write_text(md, encoding="utf-8")
        log("Wrote docs/EVAL_RESULTS.md and bench/results/results.json")
    else:
        print(md)
        log(f"Partial run: wrote bench/results/{name} (docs/EVAL_RESULTS.md left unchanged)")
    return results
