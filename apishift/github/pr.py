"""Commit the accepted changes on a branch, push, and open (or update) a pull request.

Uses the GitHub CLI (`gh`) when it's installed, and the REST API with GITHUB_TOKEN otherwise
(that's what happens inside GitHub Actions). Standard library only.
"""

from __future__ import annotations

import json
import os
import shutil
import subprocess
import urllib.request
from pathlib import Path

from ..fix.orchestrator import MigrationResult

TITLE = "Migrate removed pandas APIs to pandas 2.x"


class PRError(RuntimeError):
    pass


def _git(repo: Path, *args: str) -> str:
    p = subprocess.run(["git", *args], cwd=repo, capture_output=True, text=True)
    if p.returncode != 0:
        raise PRError(f"git {' '.join(args)} failed: {p.stderr.strip()}")
    return p.stdout.strip()


def _remote_slug(repo: Path) -> str:
    """owner/name from GITHUB_REPOSITORY or the origin URL."""
    if os.environ.get("GITHUB_REPOSITORY"):
        return os.environ["GITHUB_REPOSITORY"]
    url = _git(repo, "remote", "get-url", "origin")
    slug = url.split("github.com")[-1].lstrip(":/").removesuffix(".git")
    if slug.count("/") != 1:
        raise PRError(f"origin is not a GitHub repository: {url}")
    return slug


def _rest(method: str, url: str, token: str, payload: dict | None = None) -> dict | list:
    req = urllib.request.Request(url, method=method, data=json.dumps(payload).encode() if payload else None,
                                 headers={"Authorization": f"Bearer {token}", "Accept": "application/vnd.github+json",
                                          "X-GitHub-Api-Version": "2022-11-28", "User-Agent": "apishift"})
    with urllib.request.urlopen(req) as r:  # noqa: S310 (fixed https host)
        return json.loads(r.read() or b"{}")


def open_pull_request(repo: Path, res: MigrationResult, body: str, branch: str = "apishift/pandas-2",
                      base: str | None = None) -> str:
    files = [f.path for f in res.changed_files]
    if not files:
        raise PRError("nothing to commit")
    base = base or _git(repo, "rev-parse", "--abbrev-ref", "HEAD")
    if not _has_config(repo):  # e.g. a fresh CI runner
        _git(repo, "config", "user.name", "apishift[bot]")
        _git(repo, "config", "user.email", "apishift-bot@users.noreply.github.com")
    _git(repo, "checkout", "-B", branch)
    _git(repo, "add", "--", *files)
    _git(repo, "commit", "-m", TITLE, "-m", f"Changed {len(files)} file(s). Generated by APIShift.")
    _git(repo, "push", "--force-with-lease", "-u", "origin", branch)

    if shutil.which("gh"):
        bodyfile = repo / ".git" / "APISHIFT_PR_BODY.md"
        bodyfile.write_text(body, encoding="utf-8")
        existing = subprocess.run(["gh", "pr", "view", branch, "--json", "url", "-q", ".url"], cwd=repo,
                                  capture_output=True, text=True)
        if existing.returncode == 0 and existing.stdout.strip():
            subprocess.run(["gh", "pr", "edit", branch, "--body-file", str(bodyfile)], cwd=repo, check=True)
            return existing.stdout.strip()
        out = subprocess.run(["gh", "pr", "create", "--title", TITLE, "--body-file", str(bodyfile),
                              "--base", base, "--head", branch], cwd=repo, capture_output=True, text=True)
        if out.returncode != 0:
            raise PRError(f"gh pr create failed: {out.stderr.strip()}")
        return out.stdout.strip().splitlines()[-1]

    token = os.environ.get("GITHUB_TOKEN") or os.environ.get("GH_TOKEN")
    if not token:
        raise PRError("pushed the branch, but neither `gh` nor GITHUB_TOKEN is available to open the PR")
    slug = _remote_slug(repo)
    api = f"https://api.github.com/repos/{slug}/pulls"
    owner = slug.split("/")[0]
    found = _rest("GET", f"{api}?head={owner}:{branch}&state=open", token)
    if found:
        _rest("PATCH", f"{api}/{found[0]['number']}", token, {"body": body})
        return found[0]["html_url"]
    pr = _rest("POST", api, token, {"title": TITLE, "head": branch, "base": base, "body": body})
    return pr["html_url"]


def _has_config(repo: Path) -> bool:
    p = subprocess.run(["git", "config", "--get", "user.email"], cwd=repo, capture_output=True, text=True)
    return p.returncode == 0 and bool(p.stdout.strip())
